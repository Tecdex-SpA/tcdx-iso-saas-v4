#!/usr/bin/env node
'use strict';

const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const [resultsPath, outputPath] = process.argv.slice(2);
if (!resultsPath || !outputPath) {
  console.error('Usage: write-phase5-5-browser-evidence.js <playwright-json> <output-md>');
  process.exit(2);
}

const payload = JSON.parse(fs.readFileSync(resultsPath, 'utf8'));
const suites = payload.suites || [];
const specs = [];

function walk(suite) {
  for (const spec of suite.specs || []) specs.push(spec);
  for (const child of suite.suites || []) walk(child);
}
for (const suite of suites) walk(suite);

const tests = specs.flatMap((spec) => spec.tests.map((test) => ({
  title: spec.title,
  ok: spec.ok === true && test.status === 'expected',
  outcome: test.status,
  project: test.projectName,
  results: test.results.map((result) => ({
    status: result.status,
    duration: result.duration,
    retry: result.retry,
    error: result.error?.message || null,
  })),
})));

const failed = tests.filter((test) => !test.ok);
const status = failed.length ? 'NOT_READY' : 'COMPLETED';
function safeExec(command, args) {
  try {
    return execFileSync(command, args, { cwd: process.cwd(), encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  } catch {
    return 'unavailable';
  }
}

function readPackageVersion(relativePath) {
  try {
    return JSON.parse(fs.readFileSync(path.join(process.cwd(), relativePath), 'utf8')).version || 'unavailable';
  } catch {
    return 'unavailable';
  }
}

const totalDurationMs = tests.reduce((sum, test) => sum + test.results.reduce((inner, result) => inner + (Number(result.duration) || 0), 0), 0);
const branch = safeExec('git', ['branch', '--show-current']);
const commit = safeExec('git', ['rev-parse', 'HEAD']);
const playwrightVersion = readPackageVersion('frontend/node_modules/@playwright/test/package.json');
const lines = [
  '# Browser E2E Evidence - Phase 5.5',
  '',
  `Status: ${status}.`,
  `Date: ${new Date().toISOString()}.`,
  `Branch: ${branch}.`,
  `Commit: ${commit}.`,
  '',
  '## Command',
  '',
  '`npm run phase5-5:browser-e2e`',
  '',
  '## Runtime',
  '',
  `- Browser: Chromium via Playwright ${playwrightVersion}.`,
  '- PostgreSQL: Docker fixture `postgres:16-alpine`.',
  '- Backend: local Express runtime at `http://127.0.0.1:4105` against PostgreSQL Docker fixture.',
  '- Frontend: local Next.js runtime at `http://localhost:3105`.',
  '- Data: synthetic Tenant A/B records generated by the runner.',
  '- Fixtures: Tenant A, Tenant B, tenant admin A, tenant admin B, restricted user A, roles, permissions, capabilities and synthetic Phase 5.5 records.',
  '- Production: not used.',
  `- Duration: ${totalDurationMs}ms across ${tests.length} browser scenarios.`,
  '',
  '## Scenarios',
  '',
  ...tests.map((test) => `- ${test.ok ? 'passed' : 'failed'} · ${test.title} · ${test.project || 'chromium'} · ${test.results.map((result) => `${result.status}/${result.duration}ms`).join(', ')}`),
  '',
  '## Coverage',
  '',
  '- Login through `/login`.',
  '- Tenant context for Tenant A and Tenant B.',
  '- Portal GRC load.',
  '- Metric builder: create, source config, preview, publish, calculate, result.',
  '- Survey builder: create, version, publish, campaign, official scoring.',
  '- Assurance builder: create, execute, complete, review, sample size.',
  '- Loss analytics: create, confirm, official loss metric.',
  '- Dashboard builder: create, widget, publish, snapshot, render.',
  '- Report Studio: create, generate PDF/DOCX/XLSX, approve, download.',
  '- Permission denial for restricted user.',
  '- Tenant B isolation from Tenant A metric code.',
  '- Cross-channel consistency for Portal GRC, metric domain, dashboard snapshot and report artifacts.',
  '',
  '## Downloaded artifact checks',
  '',
  '- PDF: downloaded through backend, status 200, `Content-Type: application/pdf`, non-empty body.',
  '- DOCX: downloaded through backend, status 200, OOXML MIME containing `wordprocessingml`, non-empty body.',
  '- XLSX: downloaded through backend, status 200, OOXML MIME containing `spreadsheetml`, non-empty body.',
  '- Content-Disposition and filename are validated by the browser test for every download.',
  '- Deep PDF/DOCX/XLSX open/checksum/formula-injection validation is covered by `npm run phase5-5:artifact-validation`.',
  '',
  '## Artifacts',
  '',
  `- Playwright JSON: ${path.relative(process.cwd(), resultsPath)}`,
  '- Playwright HTML report: `artifacts/phase5-5/playwright-report`',
  '- Screenshots/traces: retained only on failure by Playwright configuration.',
  '- Secrets: JWTs, passwords and database credentials are not written to this evidence file.',
  '',
  '## Corrections validated in this run',
  '',
  '- Login uses the real `/api/auth/login` request without forced click.',
  '- Tenant context is backed by synthetic UUID tenants only.',
  '- Builders call backend APIs for preview, persistence, publication, execution, history, explanation and lineage.',
  '- Restricted user denial is verified by backend response, not only hidden UI.',
  '- Tenant B cannot discover Tenant A operational entities by UI/API scenario.',
  '',
  '## Result',
  '',
  failed.length
    ? `Blocked by ${failed.length} browser E2E failure(s).`
    : `All ${tests.length} browser E2E scenarios passed without retries or skipped cases.`,
];

fs.writeFileSync(outputPath, `${lines.join('\n')}\n`);
console.log(JSON.stringify({ status, tests: tests.length, failed: failed.length }));
