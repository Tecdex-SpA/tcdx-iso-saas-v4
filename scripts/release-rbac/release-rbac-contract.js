const ROLE_PERMISSION_MATRIX = Object.freeze(Object.fromEntries(
  CANONICAL_ROLES.map((role) => [role, new Set(ROLE_ALLOWED[role] || [])])
));

const DEALER_AUTHORIZATION_DECISION = Object.freeze({
  decision: 'SPECIAL_SCOPE_WITH_MINIMAL_PORTAL_PERMISSIONS',
  scope_authority: 'dealer_tenants/dealer_tenant_access assignment',
  notes: 'Dealer does not receive general tenant read/write permissions. Portal capabilities require assignment plus minimal dealer portal RBAC keys.',
});

function permissionGroup(permission) {
  return String(permission || '').split('.')[0] || 'runtime';
}

function rolesAllowedForPermission(permission) {
  return CANONICAL_ROLES.filter((role) => ROLE_PERMISSION_MATRIX[role].has(permission));
}

function matrixRows() {
  return RUNTIME_ACTIVE_PERMISSIONS.map((permission) => {
    const row = { permission };
    for (const role of CANONICAL_ROLES) {
      row[role] = ROLE_PERMISSION_MATRIX[role].has(permission) ? 'ALLOW' : 'DENY';
    }
    return row;
  });
}

function capabilityRows() {
  return COMMERCIAL_PLAN_CAPABILITIES.map((capability) => ({
    capability: capability.capability_key,
    module: capability.module_key,
    required_permission: capability.required_permission,
    roles: rolesAllowedForPermission(capability.required_permission).join(',') || 'none',
    classification: capability.classification,
    addon_key: capability.addon_key || '',
  }));
}

