function interpolate(value, params = {}) {
  return String(value || '').replace(/\{\{(\w+)\}\}/g, (_, key) => {
    const replacement = params[key];
    return replacement === undefined || replacement === null ? '' : String(replacement);
  });
}

function createReportTranslator(locale = 'es') {
  const normalized = normalizeLocale(locale);
  const current = dictionaries[normalized] || dictionaries.es;
  const fallback = dictionaries.es;

  return function rt(key, params = {}) {
    const value = current[key] || fallback[key] || key;
    return interpolate(value, params);
  };
}

function reportLocaleToIntl(locale = 'es') {
  return localeToIntl(locale);
}

