 'use strict';
const assert = require('assert');
const stats = require('./statisticalEngine.service');
function close(actual, expected, tolerance = 1e-6) { assert.ok(Math.abs(actual - expected) <= tolerance, `${actual} != ${expected}`); }
close(stats.mean([1,2,3,4]), 2.5);
close(stats.median([1,2,3,4]), 2.5);
assert.deepStrictEqual(stats.mode([1,2,2,3]), [2]);
assert.strictEqual(stats.min([3,1,2]), 1);
assert.strictEqual(stats.max([3,1,2]), 3);
assert.strictEqual(stats.range([3,1,2]), 2);
assert.strictEqual(stats.sum([1,2,3]), 6);
assert.strictEqual(stats.count([1,null,2]), 2);
close(stats.variancePopulation([1,2,3,4]), 1.25);
close(stats.varianceSample([1,2,3,4]), 1.6666666667, 1e-9);
close(stats.stddevPopulation([1,2,3,4]), Math.sqrt(1.25));
close(stats.stddevSample([1,2,3,4]), Math.sqrt(1.6666666667));
close(stats.coefficientOfVariation([1,2,3,4]), Math.sqrt(1.6666666667)/2.5);
close(stats.percentile([10,20,30,40], .75), 32.5);
assert.deepStrictEqual(stats.quartiles([10,20,30,40]), { q1: 17.5, q2: 25, q3: 32.5 });
close(stats.iqr([10,20,30,40]), 15);
close(stats.mad([1,2,3,4,100]), 1);
close(stats.zScore(3, [1,2,3,4,5]), 0);
close(stats.robustZScore(5, [1,2,3,4,5]), 1.349, 1e-12);
assert.deepStrictEqual(stats.movingAverage([1,2,3,4,5], 3), [2,3,4]);
assert.deepStrictEqual(stats.ema([1,2,3], 3), [1,1.5,2.25]);
const regression = stats.linearRegression([{x:1,y:2},{x:2,y:4},{x:3,y:6}]);
close(regression.slope, 2); close(regression.intercept, 0); close(regression.rSquared, 1);
assert.strictEqual(stats.absoluteVariation(120, 100), 20);
assert.deepStrictEqual(stats.percentageVariation(120, 100), { status: 'calculated', value: 20, absoluteVariation: 20 });
assert.strictEqual(stats.percentageVariation(5, 0).status, 'not_calculable');
close(stats.confidenceIntervalProportion(50, 100).p, .5);
assert.strictEqual(stats.wilsonInterval(50, 100).method, 'wilson');
close(stats.pearson([1,2,3], [2,4,6]), 1);
close(stats.spearman([1,2,3], [3,2,1]), -1);
close(stats.cronbachAlpha([[1,2,3],[2,3,4],[3,4,5],[4,5,6]]), 1);
close(stats.sampleSize({ z: 1.96, p: .5, e: .05, population: 1000 }).adjusted, 277.7445, 0.01);
const rngA = stats.createSeededRng(123); const rngB = stats.createSeededRng(123);
close(rngA(), rngB());
assert.strictEqual(stats.poissonSample(1, stats.createSeededRng(42)), stats.poissonSample(1, stats.createSeededRng(42)));
close(stats.pertSample({ min: 1, mode: 2, max: 5 }, stats.createSeededRng(7)), stats.pertSample({ min: 1, mode: 2, max: 5 }, stats.createSeededRng(7)));
close(stats.lognormalSample({ mu: 0, sigma: .2 }, stats.createSeededRng(9)), stats.lognormalSample({ mu: 0, sigma: .2 }, stats.createSeededRng(9)));
const mc1 = stats.monteCarlo({ iterations: 1000, seed: 42, frequency: { type: 'poisson', lambda: 1 }, severity: { type: 'fixed', value: 100 }, threshold: 200 });
const mc2 = stats.monteCarlo({ iterations: 1000, seed: 42, frequency: { type: 'poisson', lambda: 1 }, severity: { type: 'fixed', value: 100 }, threshold: 200 });
close(mc1.expectedValue, mc2.expectedValue); close(mc1.p95, mc2.p95); assert.ok(mc1.p95 >= mc1.p50);
assert.throws(() => stats.varianceSample([1]), /Muestra insuficiente/);
process.stdout.write('phase5-5 statisticalEngine tests OK\n');
